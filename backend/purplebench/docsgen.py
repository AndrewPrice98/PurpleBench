"""Generate ``docs/COVERAGE.md``: Sigma support of the bundled rules and the coverage of the demo runs.

Everything in the file is computed from the committed rules and ``data/demo_fixture.json`` (built by the real
evaluator), so ``python -m purplebench docs --check`` fails when either changed and the file did not.
The hand-written description of the supported Sigma subset stays in ``docs/SIGMA_SUPPORT.md``.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from . import config, library, rulesets

OUT = config.REPO_DIR / "docs" / "COVERAGE.md"
DRL = rulesets.DRL_URL
STATUS_ORDER = ("detected", "partial", "missed", "telemetry_gap", "untested", "did_not_run")


def _cell(text: object) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def _rule_label(rule) -> str:
    return f"{_cell(rule.title)} ({_cell(rule.author) or 'author unknown'})"


def render(rules_dir: Path | None = None, fixture_path: Path | None = None) -> str:
    rules = rulesets.load_all_rules(rules_dir)
    by_id = {r.id: r for r in rules.values()}
    fixture = json.loads((fixture_path or config.DEMO_FIXTURE).read_text(encoding="utf-8"))
    names = {t.attack_id: t.name for t in library.list_techniques()}

    out: list[str] = []
    w = out.append
    w("# Sigma support and coverage")
    w("")
    w("<!-- Generated by `python -m purplebench docs`; do not edit. `python -m purplebench docs --check` fails when it is stale. -->")
    w("")
    w("This file is computed from the bundled rules in `backend/rules/` and the demo runs in "
      "`backend/data/demo_fixture.json`. The rules that PurpleBench's own evaluator supports are described in "
      "[SIGMA_SUPPORT.md](SIGMA_SUPPORT.md). Rules from SigmaHQ are under the "
      f"[Detection Rule License 1.1]({DRL}); every rule below is shown with its author.")
    w("")
    w("**What the numbers mean.** Coverage here is \"this rule set on this recorded telemetry\". A technique is "
      "`missed` when no rule in the set fired on it. It says nothing about any product, and nothing was executed.")
    w("")

    # -- rule inventory -------------------------------------------------------------------------
    w("## Bundled rules")
    w("")
    counts = Counter((r.origin or "?", r.status) for r in rules.values())
    w("| Rule set | Rules | Evaluated by PurpleBench | Unsupported |")
    w("|---|---|---|---|")
    for origin in rulesets.ORIGINS:
        ok, bad = counts[(origin, "ok")], counts[(origin, "unsupported")]
        w(f"| {origin} | {ok + bad} | {ok} | {bad} |")
    total_ok = sum(v for (o, s), v in counts.items() if s == "ok")
    total_bad = sum(v for (o, s), v in counts.items() if s == "unsupported")
    w(f"| **all** | **{total_ok + total_bad}** | **{total_ok}** | **{total_bad}** |")
    w("")
    unsupported = sorted((r for r in rules.values() if r.status == "unsupported"), key=lambda r: (r.origin or "", r.title))
    if unsupported:
        w("Rules outside the supported subset are reported as `unsupported` with the reason; they are never "
          "evaluated as \"no match\".")
        w("")
        w("| Rule | Author | Reason |")
        w("|---|---|---|")
        for r in unsupported:
            w(f"| {_cell(r.title)} | {_cell(r.author) or 'unknown'} | {_cell(r.reason)} |")
    else:
        w("Every bundled rule is inside the supported subset.")
    w("")
    cats = Counter(f"{r.logsource.get('category') or r.logsource.get('service') or '(none)'}" for r in rules.values())
    w("Rules by log source category or service: " + ", ".join(f"`{k}` {v}" for k, v in sorted(cats.items())) + ".")
    w("")

    # -- demo progression -----------------------------------------------------------------------
    w("## Demo runs: coverage by rule set version")
    w("")
    w("Each row is a rule set evaluated over the recorded telemetry (detected techniques out of tested techniques; "
      "`untested` and `did_not_run` do not count as tested).")
    w("")
    campaigns = [c["name"] for c in fixture["campaigns"]]
    w("| Rule set | All techniques | " + " | ".join(_cell(c) for c in campaigns) + " |")
    w("|---|---|" + "---|" * len(campaigns))
    for row in fixture["meta"]["progression"]:
        cells = [f"{row[k]['detected']} of {row[k]['tested']} ({row[k]['score']}%)" for k in ["all", *campaigns]]
        w(f"| {row['version']} | " + " | ".join(cells) + " |")
    w("")

    # -- latest run per campaign ----------------------------------------------------------------
    w("## Latest demo run of each campaign")
    w("")
    latest: dict[int, dict] = {}
    for run in fixture["runs"]:
        latest[run["campaign_id"]] = run
    ruleset_version = {s["id"]: s["version"] for s in fixture["rulesets"]}
    for camp in fixture["campaigns"]:
        run = latest[camp["id"]]
        counts = Counter(e["status"] for e in run["executions"])
        w(f"### {camp['name']}")
        w("")
        w(f"Run {run['id']}, rule set {ruleset_version[run['ruleset_id']]}, recorded mode. "
          + ", ".join(f"{counts[s]} {s.replace('_', ' ')}" for s in STATUS_ORDER if counts[s]) + ".")
        w("")
        w("| Technique | Name | Status | Rules that fired (author) |")
        w("|---|---|---|---|")
        for e in sorted(run["executions"], key=lambda e: e["technique_id"]):
            fired = [h for h in e["hits"] if not h["noisy"]]
            labels = [_rule_label(by_id[h["rule_id"]]) + ("" if h["relation"] == "exact" else f" [{h['relation']}]")
                      for h in fired if h["rule_id"] in by_id]
            noisy = [_rule_label(by_id[h["rule_id"]]) for h in e["hits"] if h["noisy"] and h["rule_id"] in by_id]
            shown = "; ".join(labels) or (f"none credited; noisy only: {'; '.join(noisy)}" if noisy else "-")
            w(f"| {e['technique_id']} | {_cell(names.get(e['technique_id']) or e['name'])} | {e['status'].replace('_', ' ')} "
              f"| {shown} |")
        w("")
    w("`untested` means the technique has no usable recorded telemetry in this data set. "
      "`[related]` and `[parent]` mark credit for a rule tagged with a related technique or the parent technique, "
      "which gives `partial`, not `detected`. Noisy rules (rules that also fire on the benign baseline) earn no credit and "
      "are named only when nothing else fired.")
    w("")
    return "\n".join(out)
