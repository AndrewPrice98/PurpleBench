"""Technique library: ATT&CK v20 techniques and the Atomic Red Team test metadata for each.

The data is committed in ``data/library.json`` (generated by ``scripts/build_datasets.py`` from the
Atomic Red Team YAML, MIT licence). Command text is **data for display only**: nothing in PurpleBench
executes it.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Any

DATA_DIR = Path(os.environ.get("PURPLEBENCH_DATA_DIR") or Path(__file__).resolve().parent.parent / "data")

# ATT&CK Enterprise v20 tactics (v19 split Defense Evasion into Stealth and Defense Impairment).
TACTICS: dict[str, str] = {
    "reconnaissance": "Reconnaissance",
    "resource-development": "Resource Development",
    "initial-access": "Initial Access",
    "execution": "Execution",
    "persistence": "Persistence",
    "privilege-escalation": "Privilege Escalation",
    "stealth": "Stealth",
    "defense-impairment": "Defense Impairment",
    "credential-access": "Credential Access",
    "discovery": "Discovery",
    "lateral-movement": "Lateral Movement",
    "collection": "Collection",
    "command-and-control": "Command and Control",
    "exfiltration": "Exfiltration",
    "impact": "Impact",
}

EXECUTION_ATOMIC = "atomic test"
EXECUTION_RECORDED = "recorded technique execution"

_ARG_RX = re.compile(r"#\{([^}]+)\}")


@dataclass(frozen=True)
class AtomicTest:
    guid: str
    name: str
    description: str
    executor: str
    command: str
    cleanup_command: str
    elevation_required: bool
    input_arguments: dict[str, str]
    supported_platforms: tuple[str, ...]
    source_url: str

    @property
    def command_resolved(self) -> str:
        """The command with ``#{arg}`` placeholders replaced by their default values (display only)."""
        return _ARG_RX.sub(lambda m: self.input_arguments.get(m.group(1), m.group(0)), self.command)


@dataclass(frozen=True)
class Technique:
    attack_id: str
    dataset_id: str  # Splunk's folder name; differs from attack_id for IDs renumbered in ATT&CK v19
    name: str
    tactics: tuple[str, ...]
    execution_kind: str
    atomic: AtomicTest | None
    dataset: dict[str, Any]
    link: str
    telemetry: str  # path of the recorded events, relative to data/telemetry
    note: str | None = None
    extra: dict[str, Any] = field(default_factory=dict, compare=False)

    @property
    def tactic_names(self) -> tuple[str, ...]:
        return tuple(TACTICS[t] for t in self.tactics)


def _atomic(d: dict[str, Any] | None) -> AtomicTest | None:
    if d is None:
        return None
    return AtomicTest(
        guid=d["guid"], name=d["name"], description=d["description"], executor=d["executor"],
        command=d["command"], cleanup_command=d["cleanup_command"],
        elevation_required=bool(d["elevation_required"]), input_arguments=dict(d["input_arguments"]),
        supported_platforms=tuple(d["supported_platforms"]), source_url=d["source_url"],
    )


@lru_cache(maxsize=4)
def _load(path: str) -> tuple[dict[str, Any], tuple[Technique, ...]]:
    with open(path, encoding="utf-8") as fh:
        raw = json.load(fh)
    techs = tuple(
        Technique(
            attack_id=t["attack_id"], dataset_id=t["dataset_id"], name=t["name"], tactics=tuple(t["tactics"]),
            execution_kind=t["execution_kind"], atomic=_atomic(t["atomic"]), dataset=t["dataset"], link=t["link"],
            telemetry=t["telemetry"], note=t.get("note"),
        )
        for t in raw["techniques"]
    )
    return raw, techs


def library_meta(path: Path | str | None = None) -> dict[str, Any]:
    """Library header: ATT&CK version and the Atomic Red Team source commit/licence."""
    raw, _ = _load(str(path or DATA_DIR / "library.json"))
    return {k: v for k, v in raw.items() if k != "techniques"}


def list_techniques(path: Path | str | None = None) -> list[Technique]:
    return list(_load(str(path or DATA_DIR / "library.json"))[1])


def get_technique(attack_id: str, path: Path | str | None = None) -> Technique | None:
    """Look up by v20 ATT&CK id, or by the Splunk dataset id alias (e.g. ``T1562.001`` -> ``T1685``)."""
    for t in list_techniques(path):
        if attack_id in (t.attack_id, t.dataset_id):
            return t
    return None


def covered_tactics(path: Path | str | None = None) -> list[str]:
    """Tactics (v20 ids) that at least one technique in the library belongs to, in ATT&CK order."""
    have = {x for t in list_techniques(path) for x in t.tactics}
    return [t for t in TACTICS if t in have]
